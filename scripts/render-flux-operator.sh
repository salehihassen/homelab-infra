#!/usr/bin/env bash
# Regenerate the vendored operator/chart, not the operator-owned Flux controllers.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
helm pull oci://ghcr.io/controlplaneio-fluxcd/charts/flux-operator \
  --version 0.62.1 --destination "$work"
# Chart OCI manifest digest:
# sha256:1135514a01cc11e206f5ff0b568ac30d9defd675022b7a9da88d4a3474fbdf13
printf '%s  %s\n' \
  1930755f5093b258c408a28b702c979090283e008b72d413f6e92a4b097ab908 \
  "$work/flux-operator-0.62.1.tgz" | sha256sum --check --strict
helm template flux-operator "$work/flux-operator-0.62.1.tgz" \
  --namespace flux-system --include-crds \
  --values kubernetes/infrastructure/flux-operator/values.yaml \
  > "$work/operator.yaml"
{
  printf '# Generated by scripts/render-flux-operator.sh. DO NOT EDIT.\n'
  cat "$work/operator.yaml"
} > kubernetes/infrastructure/flux-operator/operator.yaml
