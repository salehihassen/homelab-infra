#!/usr/bin/env bash
# Regenerate the vendored CloudNativePG operator manifest from its release.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
version=1.30.1
checksum=37237f145d8138256ea25ae830f87759255665ff08f8d552fdd8224a5ec032fb
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl --fail --silent --show-error --location \
  "https://github.com/cloudnative-pg/cloudnative-pg/releases/download/v${version}/cnpg-${version}.yaml" \
  -o "$work/operator.yaml"
printf '%s  %s\n' "$checksum" "$work/operator.yaml" | sha256sum --check --strict
{
  printf '# Generated by scripts/render-cloudnative-pg.sh (CloudNativePG %s). DO NOT EDIT.\n' "$version"
  cat "$work/operator.yaml"
} > kubernetes/infrastructure/cloudnative-pg/operator.yaml
